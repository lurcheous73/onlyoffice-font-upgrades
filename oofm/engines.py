APPLY_LOCK = threading.Lock()

def docker_ps() -> list[tuple[str, str]]:
    cp = sh(["docker", "ps", "--format", "{{.Names}}|{{.Image}}"]); out=[]
    for line in cp.stdout.splitlines():
        if "|" in line: out.append(tuple(line.split("|",1)))
    return out

def find_container(role: str) -> str | None:
    for name,image in docker_ps():
        line=f"{name} {image}".lower()
        if role=="community" and ("communityserver" in line or "community-server" in line): return name
        if role=="document" and ("documentserver" in line or "document-server" in line): return name
    return None

def docker_exec(container: str, *args: str, check: bool=True):
    return sh(["docker","exec",container,*args],check=check)

def build_mail_css(manifests: list[dict[str,Any]]) -> str:
    lines=["/* Generated by ONLYOFFICE Font Manager. Do not edit. */"]
    for m in manifests:
        if m.get("type")=="emoji": continue
        family=str(m["family"]).replace("\\","\\\\").replace('"','\\"')
        for item in m.get("files",[]):
            rel=item["file"].replace("\\","/"); ext=Path(rel).suffix.lower()
            fmt={".ttf":"truetype",".otf":"opentype",".woff":"woff",".woff2":"woff2"}.get(ext,"truetype")
            lines += ["@font-face {",f'  font-family: "{family}";',f'  src: url("fonts/{rel}") format("{fmt}");',f"  font-weight: {item.get('weight','400')};",f"  font-style: {item.get('style','normal')};","  font-display: swap;","}"]
    return "\n".join(lines)+"\n"

